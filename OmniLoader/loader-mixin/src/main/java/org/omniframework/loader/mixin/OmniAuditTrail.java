package org.omniframework.loader.mixin;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.spongepowered.asm.service.IMixinAuditTrail;

/**
 * Records what Mixin did to each class, into the same story the AOT pipeline tells
 * (ARCHITECTURE §8, wired to §6's audit store).
 *
 * <h2>Why this matters more than it looks</h2>
 *
 * <p>By the time a class reaches a debugger it may have been remapped ahead of time, had access
 * widened, had members stripped, and then had three mods' mixins applied to it at load. Without a
 * single record, "why does this method look nothing like the source" is unanswerable — and the
 * AOT half of that story is already in {@code audit.json}. If Mixin's half lived somewhere else,
 * a user would have to know that two separate mechanisms exist and go looking for both.
 *
 * <p>So this is deliberately the same shape as a transform pass record: who acted, on what, in
 * what order. Mixin application is <em>not</em> part of the AOT cache — target classes are not
 * known until load, which is why §6 excludes it — so these entries are per-run and live in
 * memory, not in a cache entry. Making them look the same is what lets one query answer both.
 *
 * <h2>Ordering is the payload</h2>
 *
 * <p>Two mixins that both modify one method produce different bytecode depending on which applied
 * first, and that ordering is the single most common cause of "works alone, breaks together". The
 * order of {@link #onApply} calls is therefore preserved exactly and never sorted.
 *
 * <p>Thread-safe: Mixin applies during classloading, which is parallel.
 */
public final class OmniAuditTrail implements IMixinAuditTrail {

    /** Kinds of event Mixin reports. */
    public enum Kind {
        /** A mixin was applied to a target class. */
        APPLY,
        /** A class was post-processed (e.g. accessor/proxy finalisation). */
        POST_PROCESS,
        /** Mixin generated a synthetic class. */
        GENERATE
    }

    /** One thing Mixin did to one class. */
    public record Entry(Kind kind, String className, String detail, long sequence) {

        /** Canonical constructor. */
        public Entry {
            Objects.requireNonNull(kind, "kind");
            Objects.requireNonNull(className, "className");
            Objects.requireNonNull(detail, "detail");
        }

        /** A one-line rendering, matching the transform audit's style. */
        public String describe() {
            return switch (kind) {
                case APPLY -> "mixin applied: " + detail;
                case POST_PROCESS -> "post-processed";
                case GENERATE -> "generated by: " + detail;
            };
        }
    }

    private final Map<String, List<Entry>> byClass = new ConcurrentHashMap<>();
    private final java.util.concurrent.atomic.AtomicLong sequence =
            new java.util.concurrent.atomic.AtomicLong();

    @Override
    public void onApply(String className, String mixinName) {
        record(Kind.APPLY, className, mixinName);
    }

    @Override
    public void onPostProcess(String className) {
        record(Kind.POST_PROCESS, className, "");
    }

    @Override
    public void onGenerate(String className, String generatorName) {
        record(Kind.GENERATE, className, generatorName);
    }

    private void record(Kind kind, String className, String detail) {
        String normalised = normalise(className);
        Entry entry = new Entry(kind, normalised, detail == null ? "" : detail,
                sequence.incrementAndGet());
        byClass.computeIfAbsent(normalised, ignored -> java.util.Collections.synchronizedList(
                new ArrayList<>())).add(entry);
    }

    /**
     * Everything Mixin did to a class, in application order.
     *
     * <p>Accepts either {@code a/b/C} or {@code a.b.C}: Mixin reports both forms depending on the
     * call site, and a user typing dots should not get "not found" for a class that is right
     * there.
     */
    public List<Entry> forClass(String className) {
        List<Entry> entries = byClass.get(normalise(className));
        if (entries == null) {
            return List.of();
        }
        synchronized (entries) {
            return List.copyOf(entries);
        }
    }

    /** The mixins applied to a class, in order — the answer to "who changed this method". */
    public List<String> mixinsAppliedTo(String className) {
        return forClass(className).stream()
                .filter(entry -> entry.kind() == Kind.APPLY)
                .map(Entry::detail)
                .toList();
    }

    /** Every class Mixin touched this run. */
    public List<String> touchedClasses() {
        return byClass.keySet().stream().sorted().toList();
    }

    /** How many events were recorded. */
    public long eventCount() {
        return sequence.get();
    }

    /**
     * The multi-line rendering for {@code --audit <class>}, or empty when Mixin never touched it.
     *
     * <p>Returned as an {@link Optional} rather than an empty string so the caller can tell
     * "Mixin did nothing" apart from "Mixin did something unprintable" — the first is normal for
     * the overwhelming majority of classes.
     */
    public Optional<String> describeClass(String className) {
        List<Entry> entries = forClass(className);
        if (entries.isEmpty()) {
            return Optional.empty();
        }
        StringBuilder out = new StringBuilder(className.replace('/', '.'));
        out.append(" (load-time, this run)");
        for (Entry entry : entries) {
            out.append("\n  ").append(entry.describe());
        }
        return Optional.of(out.toString());
    }

    /** A snapshot of the whole trail, for diagnostics dumps. */
    public Map<String, List<Entry>> snapshot() {
        Map<String, List<Entry>> copy = new LinkedHashMap<>();
        touchedClasses().forEach(className -> copy.put(className, forClass(className)));
        return copy;
    }

    private static String normalise(String className) {
        return Objects.requireNonNull(className, "className").replace('.', '/');
    }
}
